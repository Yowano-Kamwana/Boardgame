// Packed .gltf.json -> plain JS module (quantized geometry, base64) + separate WebP texture files.
// The game then needs no WebAssembly, no data: URLs and no blob: URLs to show a figure.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';
import fs from 'fs';
import path from 'path';
await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
const [hiSrc, loSrc, outDir, name] = process.argv.slice(2);
const read = async (f) => io.readJSON({ json: JSON.parse(fs.readFileSync(f, 'utf8')), resources: {} });
const hi = await read(hiSrc), lo = await read(loSrc);
fs.mkdirSync(path.join(outDir, 'lite'), { recursive: true });

const root = hi.getRoot();
const node = root.listNodes().find((n) => n.getMesh());
const prim = node.getMesh().listPrimitives()[0];
const mat = node.getWorldMatrix();
const acc = (s) => prim.getAttribute(s);
const P = acc('POSITION'), N = acc('NORMAL'), T = acc('TEXCOORD_0'), I = prim.getIndices();
const n = P.getCount();
const el = [0, 0, 0], tmp = [0, 0, 0];
const pos = new Float32Array(n * 3), nrm = new Float32Array(n * 3), uv = new Float32Array(n * 2);
const xf = (m, v, w) => [m[0] * v[0] + m[4] * v[1] + m[8] * v[2] + w * m[12], m[1] * v[0] + m[5] * v[1] + m[9] * v[2] + w * m[13], m[2] * v[0] + m[6] * v[1] + m[10] * v[2] + w * m[14]];
for (let i = 0; i < n; i++) {
  const p = xf(mat, P.getElement(i, el), 1); pos.set(p, i * 3);
  const q = xf(mat, N.getElement(i, tmp), 0); const L = Math.hypot(...q) || 1; nrm.set(q.map((x) => x / L), i * 3);
  uv.set(T.getElement(i, [0, 0]), i * 2);
}
const mn = [Infinity, Infinity, Infinity], mx = [-Infinity, -Infinity, -Infinity];
for (let i = 0; i < n; i++) for (let a = 0; a < 3; a++) { mn[a] = Math.min(mn[a], pos[i * 3 + a]); mx[a] = Math.max(mx[a], pos[i * 3 + a]); }
const umn = [Infinity, Infinity], umx = [-Infinity, -Infinity];
for (let i = 0; i < n; i++) for (let a = 0; a < 2; a++) { umn[a] = Math.min(umn[a], uv[i * 2 + a]); umx[a] = Math.max(umx[a], uv[i * 2 + a]); }
const qp = new Uint16Array(n * 3), qn = new Int8Array(n * 4), qu = new Uint16Array(n * 2);
for (let i = 0; i < n; i++) {
  for (let a = 0; a < 3; a++) qp[i * 3 + a] = Math.round((pos[i * 3 + a] - mn[a]) / ((mx[a] - mn[a]) || 1) * 65535);
  for (let a = 0; a < 3; a++) qn[i * 4 + a] = Math.round(nrm[i * 3 + a] * 127);
  for (let a = 0; a < 2; a++) qu[i * 2 + a] = Math.round((uv[i * 2 + a] - umn[a]) / ((umx[a] - umn[a]) || 1) * 65535);
}
const idxArr = I.getArray();
const qi = n < 65536 ? Uint16Array.from(idxArr) : Uint32Array.from(idxArr);
const parts = [qp, qn, qu, qi].map((a) => Buffer.from(a.buffer, a.byteOffset, a.byteLength));
// keep each part 4-byte aligned
const pad = (b) => Buffer.concat([b, Buffer.alloc((4 - (b.length % 4)) % 4)]);
const bufs = parts.map(pad);
const meta = { v: n, i: qi.length, i32: qi instanceof Uint32Array, min: mn, max: mx, umin: umn, umax: umx, sizes: bufs.map((b) => b.length) };
const b64 = Buffer.concat(bufs).toString('base64');
fs.writeFileSync(path.join(outDir, `${name}.js`), `// ${name}: generated by tofigure.mjs from the Tripo model\nexport const meta = ${JSON.stringify(meta)};\nexport const data = '${b64}';\n`);

// textures, by slot
const slots = (doc) => {
  const m = doc.getRoot().listMaterials()[0];
  return { c: m.getBaseColorTexture(), n: m.getNormalTexture(), r: m.getMetallicRoughnessTexture() };
};
for (const [doc, dir] of [[hi, outDir], [lo, path.join(outDir, 'lite')]]) {
  for (const [k, t] of Object.entries(slots(doc))) if (t) fs.writeFileSync(path.join(dir, `${name}-${k}.webp`), Buffer.from(t.getImage()));
}
const kb = (f) => (fs.statSync(f).size / 1024).toFixed(0);
console.log(name, 'verts', n, 'tris', qi.length / 3, 'geom', kb(path.join(outDir, `${name}.js`)) + 'KB', 'c', kb(path.join(outDir, `${name}-c.webp`)) + 'KB');
